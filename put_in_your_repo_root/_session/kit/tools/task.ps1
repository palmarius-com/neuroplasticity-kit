# task.ps1 - open, close or switch a task and rebuild the index (_session/this_repo/tasklist.md).
#
#   task.ps1 open  -Title "Short title"     new file in tasks/open, journal line, becomes current task
#   task.ps1 close -Id T029                 moves the file, unchanged, to tasks/closed, journal line
#   task.ps1 switch -Id T017                sets the current task (the hooks stamp with it)
#   task.ps1 index                          only rebuilds tasklist.md
#
# No git command is run. Closing is a plain file move; git shows it as a rename.

param(
    [Parameter(Mandatory = $true, Position = 0)][ValidateSet('open', 'close', 'switch', 'index')][string]$Action,
    [string]$Title = '',
    [string]$Id = ''
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'lib.ps1')
$p = Get-SessionPaths

function Set-CurrentTask([string]$task) { Write-TextFile (Join-Path $p.This 'current_task') @($task) }

function Write-Index {
    $tasks = @(Get-TaskFiles)
    $open = @($tasks | Where-Object { $_.State -eq 'open' })
    $out = New-Object System.Collections.Generic.List[string]
    $out.Add('# Task List')
    $out.Add('')
    $out.Add('GENERATED by `_session/kit/tools/task.ps1`. Do not edit. One file per task;')
    $out.Add('the folder is the status. Times: `timetable.md`.')
    $out.Add('')
    $out.Add(('Open: {0}. Closed: {1}. Next free: {2}. Current: {3}.' -f $open.Count, ($tasks.Count - $open.Count), (Get-NextTaskId), (Get-CurrentTask)))
    $out.Add('')
    $out.Add('## Open')
    $out.Add('')
    $out.Add('| Task | Title | File |')
    $out.Add('|---|---|---|')
    foreach ($t in $open) { $out.Add(('| {0} | {1} | `tasks/open/{2}` |' -f $t.Id, $t.Title, (Split-Path -Leaf $t.Path))) }
    $out.Add('')
    $out.Add('## Closed')
    $out.Add('')
    $out.Add('| Task | Title |')
    $out.Add('|---|---|')
    foreach ($t in ($tasks | Where-Object { $_.State -eq 'closed' })) { $out.Add(('| {0} | {1} |' -f $t.Id, $t.Title)) }
    Write-TextFile (Join-Path $p.This 'tasklist.md') $out.ToArray()
}

if ($Id) { $Id = $Id.ToUpperInvariant() }

switch ($Action) {
    'open' {
        if (-not $Title) { throw 'open needs -Title' }
        $new = Get-NextTaskId
        $file = Join-Path $p.Open ($new.ToLowerInvariant() + '.md')
        $template = Read-TextLines (Join-Path $p.Kit 'templates\task.md')
        if ($template.Count -eq 0) { $template = @('# TNNN: Title', '', '## Description', '', '## Work Done', '', '## Findings', '', '## Open') }
        $template[0] = "# ${new}: $Title"
        if (-not (Test-Path -LiteralPath $p.Open)) { New-Item -ItemType Directory -Force -Path $p.Open | Out-Null }
        Write-TextFile $file $template
        Set-CurrentTask $new
        $line = Add-JournalLine $new ("opened: $Title")
        Write-Index
        Write-Output ("Opened {0}: {1}" -f $new, $file)
        Write-Output $line
    }
    'close' {
        if ($Id -notmatch '^T\d{3,}$') { throw 'close needs -Id Tnnn' }
        $name = $Id.ToLowerInvariant() + '.md'
        $from = Join-Path $p.Open $name
        if (-not (Test-Path -LiteralPath $from)) { throw "not an open task: $Id" }
        if (-not (Test-Path -LiteralPath $p.Closed)) { New-Item -ItemType Directory -Force -Path $p.Closed | Out-Null }
        Move-Item -LiteralPath $from -Destination (Join-Path $p.Closed $name)
        $line = Add-JournalLine $Id 'closed'
        if ((Get-CurrentTask) -eq $Id) { Set-CurrentTask 'T000' }
        Write-Index
        Write-Output ("Closed {0}." -f $Id)
        Write-Output $line
    }
    'switch' {
        if ($Id -notmatch '^T\d{3,}$') { throw 'switch needs -Id Tnnn' }
        if ($Id -ne 'T000' -and -not (Test-Path -LiteralPath (Join-Path $p.Open ($Id.ToLowerInvariant() + '.md')))) { throw "not an open task: $Id" }
        Set-CurrentTask $Id
        Write-Index
        Write-Output ("Current task: {0}" -f $Id)
    }
    'index' {
        Write-Index
        Write-Output 'tasklist.md rebuilt.'
    }
}
